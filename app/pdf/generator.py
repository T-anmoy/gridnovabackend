def _section_title(section_id: str) -> str:
    return _SECTION_TITLES.get(section_id, section_id.replace("_", " ").title())


def _e(value) -> str:
    """Escape a value for the HTML template. Every interpolated value goes through
    this: customer names and overviews are typed by website visitors, and WeasyPrint
    would otherwise render any markup in them. Line breaks survive because the
    .section blocks use white-space: pre-line."""
    return html.escape("" if value is None else str(value), quote=True)


_CSS_COLOR_RE = re.compile(r"^#[0-9a-fA-F]{3,8}$")


def _css_color(value, default: str) -> str:
    """Letterhead colours land inside the <style> block, where HTML escaping is no
    protection — only a plain hex colour is used, anything else falls back."""
    return value if isinstance(value, str) and _CSS_COLOR_RE.match(value) else default


def _render_body_sections(proposal_data: dict, content_config: dict) -> str:
    """Render the composed, ordered section list into HTML.

    New proposals carry a resolved `sections` list (from the content engine). For
    backward compatibility with any older row that lacks it, fall back to the flat
    scope/terms fields the previous format used.
    """
    sections = proposal_data.get("sections")
    if isinstance(sections, list) and sections:
        html_parts = []
        for section in sections:
            if section.get("id") == "cover_letter_intro":
                # Already surfaced as the Project Overview lead-in — skip duplicate.
                continue
            title = _section_title(section.get("id", ""))
            body = section.get("body", "")
            html_parts.append(f'<h2>{_e(title)}</h2>\n<div class="section">{_e(body)}</div>')
        return "\n\n".join(html_parts)

    # Legacy fallback.
    scope = proposal_data.get("scope_of_work", "[PLACEHOLDER]")
    terms = proposal_data.get("terms_and_conditions", "[PLACEHOLDER]")
    return (
        f'<h2>Scope of Work</h2>\n<div class="section">{_e(scope)}</div>\n\n'
        f'<h2>Terms &amp; Conditions</h2>\n<div class="section">{_e(terms)}</div>'
    )


def _build_html(proposal_data: dict, content_config: dict) -> str:
    company = content_config.get("company", {})
    letterhead = content_config.get("letterhead", {})
    accent = _css_color(letterhead.get("accent_color"), "#f7a800")
    primary = _css_color(letterhead.get("primary_color"), "#0e2a63")

    from app.proposals.acceptance import validity_days as proposal_validity_days

    total_value = proposal_data.get("total_value")
    # Documents print amounts as the price list says: "Rs 1,23,456.78".
    from app.pricing.price_list import document_amount
    value_str = document_amount(total_value) if total_value else "[PLACEHOLDER]"

    notes = []
    if proposal_data.get("requires_manager_signoff", False):
        notes.append(
            '<div class="signoff-flag"><strong>Manager Sign-Off Required:</strong> '
            "This proposal exceeds the standard approval threshold and requires "
            "management sign-off before it can be sent.</div>"
        )
    if proposal_data.get("used_fallback_template", False):
        notes.append(
            '<div class="signoff-flag"><strong>Manual Review Required:</strong> '
            "This proposal did not match a known project profile and used a generic "
            "fallback scope. Review and complete it manually before sending.</div>"
        )

    return _PROPOSAL_HTML_TEMPLATE.format(
        accent=accent,
        primary=primary,
        company_name=_e(company.get("name", "Grid Nova Energy")),
        version=_e(proposal_data.get("version", 1)),
        customer_name=_e(proposal_data.get("customer_name", "[Customer]")),
        date=_e(format_ist_date(datetime.now(timezone.utc))),
        proposal_id=_e(proposal_data.get("proposal_id", "")),
        lead_id=_e(proposal_data.get("lead_id", "")),
        # Fixed markup built above from constants only — never from input.
        manager_signoff_note="\n".join(notes),
        total_value=_e(value_str),
        project_overview=_e(proposal_data.get("project_overview", "[PLACEHOLDER]")),
        body_sections=_render_body_sections(proposal_data, content_config),
        # config/sales_policy.yaml — the same period the accept link enforces.
        validity_days=_e(proposal_validity_days()),
        address=_e(company.get("address", "")),
        email=_e(company.get("email", "")),
        website=_e(company.get("website", "")),
    )


def render_pdf(proposal_data: dict, content_config: dict) -> bytes:
    """Render proposal HTML to PDF bytes using WeasyPrint."""
    from app.pdf.fetcher import render_pdf as render_with_safe_fetcher

    return render_with_safe_fetcher(_build_html(proposal_data, content_config))


# Re-exported for backward compatibility (existing callers/tests import this
# from here) — the real, single definition now lives in app.storage.r2, which
# app.api.routes.proposal_inputs's upload endpoint also uses, so both R2
# integrations share one exception type and one config-check, not two.
from app.storage.r2 import StorageNotConfiguredError, upload_bytes  # noqa: E402


def upload_to_r2(pdf_bytes: bytes, proposal_id: int) -> str:
    """Upload PDF to Cloudflare R2. Returns the public URL. Raises on failure."""
    key = f"proposals/{proposal_id}/{uuid.uuid4().hex}.pdf"
    return upload_bytes(key, pdf_bytes, "application/pdf")


def generate_and_upload_pdf(
    proposal_data: dict,
    content_config: dict,
    proposal_id: int,
    max_retries: int = 3,
    timeout_seconds: Optional[float] = None,
) -> Optional[str]:
    """
    Render the PDF and attempt to upload to R2 with exponential back-off.
    Returns the URL on success, None if all retries fail.
    The caller is responsible for deciding whether to block or proceed.

    `timeout_seconds`, if given, bounds the TOTAL wall-clock time spent retrying —
    a real thread can't be safely killed from outside in Python, so this is what
    keeps the background PDF-generation thread from running away indefinitely
    (e.g. full exponential back-off across every retry) when storage is down.
    """
    start = time.monotonic()

    def _remaining() -> Optional[float]:
        if timeout_seconds is None:
            return None
        return timeout_seconds - (time.monotonic() - start)

    try:
        pdf_bytes = render_pdf(proposal_data, content_config)
    except Exception as exc:
        logger.error("[FALLBACK] PDF render failed", extra={"proposal_id": proposal_id, "error": str(exc)})
        return None

    for attempt in range(1, max_retries + 1):
        remaining = _remaining()
        if remaining is not None and remaining <= 0:
            logger.error(
                "[FALLBACK] PDF generation timed out before all upload retries were attempted",
                extra={"proposal_id": proposal_id, "timeout_seconds": timeout_seconds, "attempt": attempt},
            )
            return None
        try:
            url = upload_to_r2(pdf_bytes, proposal_id)
            logger.info("PDF uploaded to R2", extra={"proposal_id": proposal_id, "url": url})
            return url
        except StorageNotConfiguredError as exc:
            # Not transient — every retry would fail identically. Fail fast instead
            # of sleeping through a full exponential back-off for nothing.
            logger.error(
                "[FALLBACK] R2 storage is not configured — not retrying",
                extra={"proposal_id": proposal_id, "error": str(exc)},
            )
            return None
        except Exception as exc:
            wait = 2 ** attempt
            logger.warning(
                "[FALLBACK] R2 upload attempt %d/%d failed — retrying in %ds",
                attempt, max_retries, wait,
                extra={"proposal_id": proposal_id, "error": str(exc)},
            )
            if attempt < max_retries:
                remaining = _remaining()
                if remaining is not None:
                    if remaining <= 0:
                        logger.error(
                            "[FALLBACK] PDF generation timed out — no time left for backoff",
                            extra={"proposal_id": proposal_id, "timeout_seconds": timeout_seconds},
                        )
                        return None
                    wait = min(wait, remaining)
                time.sleep(wait)

    logger.error(
        "[FALLBACK] All R2 upload attempts failed — PDF pending",
        extra={"proposal_id": proposal_id},
    )
    return None
