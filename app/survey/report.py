"""The site survey report PDF (S1 Step 7) — the Engineer's record of what was surveyed
and how it was reviewed. No prices: it is a technical document.

Generated by staff (Engineer, Admin) once a review exists; rendered with WeasyPrint
through app/pdf/fetcher.py (data: URIs only — the two signature images are embedded as
data URIs from private storage) and stored privately at
proposal-inputs/{inputs_id}/survey_report/{uuid}.pdf. Regenerating stores a new file and
keeps the old one. Every value an associate or customer typed is HTML-escaped.

The letterhead is the proposal PDF's company block (config/proposal_content.yaml); a
company fact still carrying a placeholder marker is left out, never printed.
"""
from __future__ import annotations

import base64
import html
import uuid
from datetime import datetime, timezone
from typing import Any, Optional

from sqlalchemy.orm import Session

from app.associates.service import AssociateError
from app.memory.models import Customer, CustomerOnboarding, Employee, ProposalInputs
from app.pdf.fonts import FONT_STACK
from app.survey import results as survey_results

PDF = "application/pdf"
PNG_MAGIC = b"\x89PNG\r\n\x1a\n"

_FIELD_LABELS = {
    "avg_monthly_units_kwh": "average monthly units",
    "avg_monthly_bill_inr": "average monthly bill",
}
_FACTOR_LABELS = {"area": "the shadow-free roof area", "load": "the sanctioned load", "usage": "the electricity use"}


def _e(value: Any) -> str:
    return html.escape("" if value is None else str(value), quote=True)


def _plain(value: Any) -> Any:
    return value.value if hasattr(value, "value") else value


def _words(value: Any) -> str:
    value = _plain(value)
    if value is None:
        return "—"
    if isinstance(value, bool):
        return "Yes" if value else "No"
    if isinstance(value, list):
        return ", ".join(_words(v) for v in value) if value else "None"
    return str(value).replace("_", " ")


def _when(value: Any) -> str:
    from app.timezones import _as_ist

    if value is None:
        return "—"
    if isinstance(value, str):
        try:
            value = datetime.fromisoformat(value)
        except ValueError:
            return value
    return _as_ist(value).strftime("%d %b %Y, %H:%M IST")


def warning_text(warning: dict) -> str:
    """One survey warning (app/survey/results.py) in plain English."""
    code, p = warning["code"], warning.get("params") or {}
    if code == "requested_above_suggested":
        return (f"The requested size ({p.get('requested_kw')} kW) is above the suggested size "
                f"({p.get('suggested_kw')} kW), which is limited by "
                f"{_FACTOR_LABELS.get(p.get('limiting_factor'), p.get('limiting_factor'))}.")
    if code == "load_enhancement_needed":
        return (f"The size needed ({p.get('required_kw')} kW) is above what the sanctioned load of "
                f"{p.get('sanctioned_load_kw')} kW allows ({p.get('max_by_load_kw')} kW): a load enhancement "
                "is needed.")
    if code == "implied_tariff_outside_range":
        return (f"The bills work out at {p.get('implied_tariff_inr_per_kwh')} rupees per unit, outside the expected "
                f"range of {p.get('min')} to {p.get('max')}.")
    if code == "units_bill_mismatch":
        field = _FIELD_LABELS.get(p.get("field"), p.get("field"))
        return (f"The {field} entered ({p.get('entered')}) differs from the average of the bills "
                f"({p.get('from_bills')}).")
    if code == "three_phase_below_min":
        return (f"The connection is three-phase but the system ({p.get('kw')} kW) is below the "
                f"{p.get('min_kw')} kW three-phase minimum.")
    if code == "fragile_roof":
        return f"The roof is {_words(p.get('roof_material'))}, which is fragile."
    if code == "overhead_line":
        return "An overhead line is recorded among the roof obstacles."
    if code == "roof_not_owned_no_noc":
        return "The customer does not own the roof and no tenant NOC is recorded."
    if code == "society_noc_missing":
        return f"The housing society's NOC has not been obtained (status: {_words(p.get('society_noc_status'))})."
    if code == "area_implausible":
        if p.get("reason") == "shadow_free_exceeds_total":
            return (f"The shadow-free area ({p.get('shadow_free_area_sqft')} sq ft) is larger than the total roof "
                    f"area ({p.get('roof_area_sqft')} sq ft).")
        return (f"The roof area ({p.get('roof_area_sqft')} sq ft) is above the expected maximum for this kind of "
                f"site ({p.get('max_plausible_sqft')} sq ft).")
    if code == "duplicate_consumer_number":
        return "Another associate has registered a customer with the same electricity consumer number."
    return code.replace("_", " ").capitalize() + "."


def _company() -> list[str]:
    """The letterhead lines — the company fields the proposal PDF prints — without any
    fact that is still a placeholder."""
    from app.placeholders.registry import MARKERS
    from app.proposals.content_engine import load_content_config

    from app.proposals.content_engine import branch_offices

    cfg = load_content_config()
    company = cfg.get("company", {})
    out = []
    for key in ("name", "address", "branch_offices", "email", "website"):
        values = branch_offices(cfg) if key == "branch_offices" else [company.get(key)]
        out += [str(v) for v in values if v and not MARKERS.search(str(v))]
    return out


def _signature_image(ref: Optional[dict]) -> Optional[str]:
    """A data: URI of the stored PNG, or None when it cannot be read as a PNG."""
    from app.storage import r2

    if not ref or not ref.get("storage_key"):
        return None
    try:
        content = r2.download_bytes(ref["storage_key"])
    except Exception:
        return None
    if not content.startswith(PNG_MAGIC):
        return None
    return "data:image/png;base64," + base64.b64encode(content).decode("ascii")


def _table(rows: list[tuple[str, Any]]) -> str:
    return "<table>" + "".join(f"<tr><th>{_e(k)}</th><td>{_e(v)}</td></tr>" for k, v in rows) + "</table>"


def _grid(headers: list[str], rows: list[list[Any]]) -> str:
    head = "".join(f"<th>{_e(h)}</th>" for h in headers)
    body = "".join("<tr>" + "".join(f"<td>{_e(c)}</td>" for c in row) + "</tr>" for row in rows)
    return f'<table class="grid"><tr>{head}</tr>{body}</table>'


def build_html(db: Session, onboarding: CustomerOnboarding, now: Optional[datetime] = None) -> str:
    from app.onboarding import service

    inputs = db.get(ProposalInputs, onboarding.proposal_inputs_id)
    customer = db.get(Customer, onboarding.customer_id)
    live = survey_results.compute(db, onboarding, include_prices=False)
    now = now or datetime.now(timezone.utc)
    letterhead = "".join(f'<div class="{"company-name" if i == 0 else "meta"}">{_e(line)}</div>'
                         for i, line in enumerate(_company()))

    address = ", ".join(str(v) for v in (inputs.full_address, inputs.district, inputs.state) if v)
    if inputs.pin_code:
        address += f" — {inputs.pin_code}"
    site = [("Client code", service.project_reference(db, onboarding)),
            ("Customer", customer.name if customer else None),
            ("Site address", address),
            ("Coordinates", f"{onboarding.site_latitude}, {onboarding.site_longitude}"
             if onboarding.site_latitude is not None else "—"),
            ("Location source", _words(onboarding.site_location_source)),
            ("Location confirmed", _when(onboarding.site_location_confirmed_at)),
            ("Survey type", _words(inputs.survey_variant))]
    connection = [("DISCOM", inputs.discom), ("Consumer number", inputs.consumer_number),
                  ("Connection phase", _words(inputs.connection_phase)),
                  ("Sanctioned load (kW)", inputs.sanctioned_load_kw)]
    for field, label in (("society_flat_count", "Flats in the society"), ("society_noc_status", "Society NOC"),
                         ("contract_demand_kva", "Contract demand (kVA)")):
        if getattr(inputs, field) is not None:
            connection.append((label, _words(getattr(inputs, field))))

    bill_rows = [[m.get("month"), m.get("units_kwh"), m.get("bill_inr") if m.get("bill_inr") is not None else "—"]
                 for m in inputs.consumption_history or []]
    bills = live["bills"]
    averages = [("Average monthly units (kWh)", bills["average_monthly_units_kwh"]),
                ("Average monthly bill (INR)", bills["average_monthly_bill_inr"]),
                ("Bill per unit (INR)", bills["implied_tariff_inr_per_kwh"])]

    roof = [("Roof accessible", _words(inputs.roof_accessible)), ("Access note", inputs.roof_access_note),
            ("Material", _words(inputs.roof_material) + (f" ({inputs.roof_material_other})"
                                                         if inputs.roof_material_other else "")),
            ("Orientation", _words(inputs.roof_orientation)), ("Floors", inputs.floors),
            ("Shading", _words(inputs.shading_condition)), ("Obstacles", _words(inputs.roof_obstacles)),
            ("Roof owned by the customer", _words(inputs.roof_ownership_confirmed)),
            ("Total roof area (sq ft)", inputs.roof_area_sqft),
            ("Shadow-free area (sq ft)", inputs.shadow_free_area_sqft),
            ("Roofs available / considered", f"{_words(inputs.roofs_available_count)} / "
                                             f"{_words(inputs.roofs_considered_count)}")]
    if inputs.tenant_noc_available is not None:
        roof.append(("Tenant NOC available", _words(inputs.tenant_noc_available)))
    section_rows = [[s.get("label"), s.get("length_m"), s.get("width_m"), s.get("obstacle_area_sqm") or "—"]
                    for s in inputs.roof_sections or []]
    layout = [("Inverter location", _words(inputs.inverter_location)),
              ("Indoor wall available", _words(inputs.indoor_wall_available)),
              ("Panels to inverter (m)", inputs.distance_panel_to_inverter_m),
              ("Inverter to LT panel (m)", inputs.distance_inverter_to_lt_panel_m),
              ("Distances measured by", _words(inputs.distance_method)),
              ("Water available", _words(inputs.water_available))]
    sizing = [("Requested size (kW)", live["requested_kw"]), ("Suggested size (kW)", live["suggested_kw"]),
              ("Limited by", _FACTOR_LABELS.get(live["limiting_factor"], "—")),
              ("Most the roof allows (kW)", live["max_by_area_kw"]),
              ("Most the sanctioned load allows (kW)", live["max_by_load_kw"]),
              ("Size the electricity use suggests (kW)", live["recommended_by_usage_kw"])]
    warnings = "".join(f"<li>{_e(warning_text(w))}</li>" for w in live["warnings"]) or "<li>None</li>"

    reviewer = db.get(Employee, inputs.feasibility_reviewed_by_id) if inputs.feasibility_reviewed_by_id else None
    review_rows = [("Outcome", _words(inputs.feasibility_outcome)),
                   ("Reviewed by", (reviewer.name if reviewer and reviewer.name else inputs.feasibility_reviewed_by_id)),
                   ("Reviewed at", _when(inputs.feasibility_reviewed_at)),
                   ("Notes", inputs.feasibility_notes or "—")]
    if inputs.survey_revised_after_review:
        review_rows.append(("Note", "The survey changed after this review."))
    conditions = "".join(f"<li>{_e(c)}</li>" for c in inputs.feasibility_conditions or [])
    revisit = "".join(f"<li>{_e(_words(i.get('section')))}{(' — ' + _e(_words(i.get('field')))) if i.get('field') else ''}"
                      f": {_e(i.get('note'))}</li>" for i in inputs.revisit_items or [])

    sigs = []
    for party, ref in (("Customer", inputs.customer_signature_ref), ("Associate", inputs.associate_signature_ref)):
        image = _signature_image(ref)
        picture = f'<img class="sig" src="{_e(image)}">' if image else "<div>(signature image not available)</div>"
        sigs.append(f'<div class="sigbox"><div><strong>{party}</strong></div>{picture if ref else "<div>Not signed</div>"}'
                    f'<div class="meta">Signed {_e(_when((ref or {}).get("signed_at")))}</div></div>')
    declaration = (f"Declared by the customer as: {_e(inputs.customer_declaration_name)}, "
                   f"{_e(_when(inputs.customer_declared_at))}" if inputs.customer_declaration_name else "")

    return f"""<!DOCTYPE html>
<html lang="en"><head><meta charset="UTF-8"><style>
  @page {{ size: A4; margin: 16mm; }}
  body {{ font-family: {FONT_STACK}; color: #111; font-size: 10pt; line-height: 1.4; }}
  .header {{ border-bottom: 3px solid #f7a800; padding-bottom: 8px; margin-bottom: 14px; }}
  .company-name {{ color: #0e2a63; font-size: 18pt; font-weight: bold; }}
  .meta {{ color: #555; font-size: 9pt; }}
  h1 {{ font-size: 14pt; margin: 6px 0 0; color: #0e2a63; }}
  h2 {{ font-size: 11pt; color: #0e2a63; border-bottom: 1px solid #ddd; margin: 14px 0 6px; padding-bottom: 3px; }}
  table {{ width: 100%; border-collapse: collapse; }}
  th {{ text-align: left; width: 38%; padding: 3px 6px; border: 0.2mm solid #bbb; background: #f3f3f3; }}
  td {{ padding: 3px 6px; border: 0.2mm solid #bbb; white-space: pre-line; }}
  table.grid th {{ width: auto; }}
  .sigbox {{ display: inline-block; width: 45%; vertical-align: top; margin-right: 4%; }}
  img.sig {{ max-width: 100%; max-height: 30mm; border: 0.2mm solid #ccc; }}
</style></head><body>
<div class="header">{letterhead}<h1>Site Survey Report</h1>
<div class="meta">Generated {_e(_when(now))}</div></div>
<h2>Customer and site</h2>{_table(site)}
<h2>Connection</h2>{_table(connection)}
<h2>Electricity bills</h2>{_grid(["Month", "Units (kWh)", "Bill (INR)"], bill_rows) if bill_rows else "<p>None recorded.</p>"}
{_table(averages)}
<h2>Roof</h2>{_table(roof)}
{_grid(["Section", "Length (m)", "Width (m)", "Obstacles (m²)"], section_rows) if section_rows else ""}
<h2>Layout and distances</h2>{_table(layout)}
<h2>Sizing and checks</h2>{_table(sizing)}
<p><strong>Warnings</strong></p><ul>{warnings}</ul>
<h2>Engineer's review</h2>{_table(review_rows)}
{"<p><strong>Conditions</strong></p><ul>" + conditions + "</ul>" if conditions else ""}
{"<p><strong>To revisit</strong></p><ul>" + revisit + "</ul>" if revisit else ""}
<h2>Signatures</h2>{"".join(sigs)}
<p>{declaration}</p>
</body></html>"""


def filename(db: Session, onboarding: CustomerOnboarding) -> str:
    from app.onboarding import service
    return f"Survey-Report-{service.project_reference(db, onboarding)}.pdf"


def generate(db: Session, onboarding: CustomerOnboarding, employee_id: str) -> ProposalInputs:
    """Render, store and record a new report. Raises AssociateError (409
    review_required) or r2.StorageNotConfiguredError. Caller commits."""
    from app.onboarding import service
    from app.pdf.fetcher import render_pdf
    from app.storage import r2

    inputs = db.get(ProposalInputs, onboarding.proposal_inputs_id)
    if inputs.feasibility_outcome is None:
        raise AssociateError("The survey report is generated after the Engineer's review.",
                             code="review_required", status_code=409)
    if not r2.is_configured():
        raise r2.StorageNotConfiguredError("R2 storage is not configured — set STORAGE_* environment variables.")
    pdf = render_pdf(build_html(db, onboarding))
    key = f"proposal-inputs/{inputs.id}/survey_report/{uuid.uuid4().hex}.pdf"
    r2.upload_bytes(key, pdf, PDF)
    before = {"survey_report_key": inputs.survey_report_key}
    inputs.survey_report_key = key
    inputs.survey_report_generated_at = datetime.now(timezone.utc)
    db.flush()
    service._audit(db, onboarding.id, "survey_report_generated", employee_id, before=before,
                   after={"survey_report_key": key,
                          "generated_at": inputs.survey_report_generated_at.isoformat()})
    return inputs


def link(db: Session, onboarding: CustomerOnboarding, performed_by: str) -> dict:
    """{url, expires_at, filename} for the latest report; the link is audited. Raises
    AssociateError (404 report_not_generated) or r2.StorageNotConfiguredError."""
    from app.onboarding import service
    from app.storage import r2

    inputs = db.get(ProposalInputs, onboarding.proposal_inputs_id)
    if not inputs.survey_report_key:
        raise AssociateError("No survey report has been generated yet.", code="report_not_generated",
                             status_code=404)
    name = filename(db, onboarding)
    url, expires_at = r2.signed_get_url(inputs.survey_report_key, filename=name)
    service.audit_document_link(db, onboarding, performed_by, "survey_report", inputs.survey_report_key, name)
    return {"url": url, "expires_at": expires_at.isoformat(), "filename": name,
            "generated_at": inputs.survey_report_generated_at.isoformat()
            if inputs.survey_report_generated_at else None}
